const strip = (w: string) => w.toLowerCase().replace(/[^a-z\p{Script=Devanagari}]/gu, '')

function buildMaps() {
  const romanToDev = new Map<string, string>()
  const devToRoman = new Map<string, string>()
  const englishDev = new Set<string>()
  const englishRoman = new Set<string>()
  const hindiRoman = new Set<string>()
  for (const [roman, dev] of HINDI_WORDS) {
    if (!romanToDev.has(roman)) romanToDev.set(roman, dev)
    if (!devToRoman.has(strip(dev))) devToRoman.set(strip(dev), roman)
    hindiRoman.add(roman)
  }
  for (const [roman, dev] of ENGLISH_LOANWORDS) {
    if (!romanToDev.has(roman)) romanToDev.set(roman, dev)
    // A Devanagari spelling that is both (रेज़ is listed under both) is treated as English.
    devToRoman.set(strip(dev), roman)
    englishDev.add(strip(dev))
    englishRoman.add(roman)
  }
  return { romanToDev, devToRoman, englishDev, englishRoman, hindiRoman }
}

const maps = buildMaps()

/** Devanagari spelling of a Roman word, if we know it. */
export const knownDevanagari = (roman: string): string | undefined =>
  maps.romanToDev.get(strip(roman))
/** Roman spelling of a Devanagari word, if we know it. */
export const knownRoman = (dev: string): string | undefined => maps.devToRoman.get(strip(dev))
/** True for a Devanagari word that is really an English one (फंडिंग). */
export const isEnglishDevanagari = (dev: string): boolean => maps.englishDev.has(strip(dev))
/** True for a Roman word that is really Hindi (kaise), as opposed to English. */
export const isHindiRoman = (roman: string): boolean => {
  const w = strip(roman)
  return maps.hindiRoman.has(w) && !maps.englishRoman.has(w)
}
export const isAmbiguousRoman = (roman: string): boolean => AMBIGUOUS_ROMAN.has(strip(roman))
export const isFillerWord = (roman: string): boolean => FILLER_WORDS.has(strip(roman))
